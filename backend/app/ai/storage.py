"""Private file storage for uploaded documents. Files live under one root folder (DOCUMENT_STORE_DIR) outside the repository.

Keys are generated by the service (engine/doc_files.storage_key) and checked again here: a key that could leave the root
(`..`, absolute path, drive letter, backslash) is refused before any file system call. Nothing here serves files by URL.
"""

import os
import tempfile
from collections.abc import Iterator
from pathlib import Path

from app.engine.doc_files import is_safe_key
from app.services.errors import ServiceError

CHUNK = 64 * 1024


class PrivateStore:
    def __init__(self, root: Path | str | None):
        if root is None or not str(root).strip():
            raise ServiceError("store_unavailable", "Document storage is not set up. Set DOCUMENT_STORE_DIR in .env to a folder outside the project.")
        self.root = Path(root)

    def _path(self, key: str) -> Path:
        if not is_safe_key(key):
            raise ServiceError("invalid_storage_key", "The storage key is not safe.")
        root = self.root.resolve()
        path = (root / key).resolve()
        if root != path and root not in path.parents:
            raise ServiceError("invalid_storage_key", "The storage key points outside the document store.")
        return path

    def save(self, key: str, data: bytes) -> None:
        """Write atomically (temp file + rename). The same key always holds the same bytes (the key contains the hash), so an
        existing file is left alone."""
        path = self._path(key)
        if path.exists():
            return
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            fd, tmp = tempfile.mkstemp(dir=path.parent, suffix=".part")
            try:
                with os.fdopen(fd, "wb") as handle:
                    handle.write(data)
                os.replace(tmp, path)
            except BaseException:
                Path(tmp).unlink(missing_ok=True)
                raise
        except OSError:
            raise ServiceError("store_unavailable", "The document store is not writable. Check DOCUMENT_STORE_DIR.") from None

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def read(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return path.read_bytes()
        except OSError:
            raise ServiceError("not_found", "The stored file is missing.") from None

    def open(self, key: str) -> Iterator[bytes]:
        """Stream the file in chunks."""
        path = self._path(key)
        try:
            handle = path.open("rb")
        except OSError:
            raise ServiceError("not_found", "The stored file is missing.") from None

        def chunks() -> Iterator[bytes]:
            with handle:
                while block := handle.read(CHUNK):
                    yield block

        return chunks()
