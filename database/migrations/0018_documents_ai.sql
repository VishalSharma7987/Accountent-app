    mean_confidence numeric(5, 4) CONSTRAINT document_texts_confidence_range CHECK (mean_confidence IS NULL OR mean_confidence BETWEEN 0 AND 1),
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT document_texts_page_key UNIQUE (document_id, page_no, method),
    CONSTRAINT document_texts_document_fk FOREIGN KEY (document_id, client_id) REFERENCES documents (id, client_id)
);

-- document <-> voucher links (the supporting document of a voucher; also used by Phase 8 "missing supporting documents")
CREATE TABLE document_vouchers (
