-- 0018: documents, Tally import / export, AI extraction and the approval queue (Phase 7, step 7.0). Schema-agnostic (see 0003).
-- RLS on every table, no policies. Functions pin their search_path; function privileges are closed at the end (0004 / 0016 / 0017 pattern).
-- There is NO money column here: extracted amounts live inside jsonb payloads as strings and are only ever read by the engine
-- (Decimal); every amount that reaches the books goes through the voucher service (V-03 and the numeric(18,4) checks of 0004).
--
-- Design in one paragraph: nothing here lets an AI or an import write to the books. A file becomes a `documents` row (hash for
-- duplicate detection, private storage key). Text is read from it (`document_texts`). A language model, when enabled for the client
-- (`client_ai_settings`), is called only through the gateway that masks personal data and stores prompt + raw answer (`llm_calls`).
-- Its validated JSON is kept unchanged forever (`extractions`); the engine recomputes tax and totals and the differences are
-- findings. Whatever the AI or a Tally file proposes becomes an `approval_queue_items` row, with a DRAFT voucher built through the
-- voucher service when the mappings are complete. The database itself refuses to approve or post such a draft until the accountant has
-- accepted its queue item (vouchers_ai_queue_guard), and refuses to accept an item that still has an unresolved error or review finding.

-- =====================================================================================================
-- Per-client switch for any LLM call: absent row = disabled
-- =====================================================================================================
CREATE TABLE client_ai_settings (
    client_id    uuid PRIMARY KEY REFERENCES clients (id),
    llm_enabled  boolean NOT NULL DEFAULT false,
    data_class   text NOT NULL DEFAULT 'synthetic' CONSTRAINT client_ai_settings_data_class_check
                 CHECK (data_class IN ('synthetic', 'anonymised', 'real_acknowledged')),
    enabled_by   text,
    enabled_at   timestamptz,
    note         text,
    updated_by   text NOT NULL CONSTRAINT client_ai_settings_updated_by_not_blank CHECK (btrim(updated_by) <> ''),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    -- enabling is an explicit, explained act: who, when, what kind of data, why
    CONSTRAINT client_ai_settings_enable_is_explicit CHECK (
        NOT llm_enabled OR (enabled_by IS NOT NULL AND enabled_at IS NOT NULL AND btrim(coalesce(note, '')) <> ''))
);

-- =====================================================================================================
-- documents: one row per stored file (private storage, never a public URL)
-- =====================================================================================================
CREATE TABLE documents (
    id                uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    client_id         uuid NOT NULL REFERENCES clients (id),
    financial_year_id uuid,
    doc_type          text NOT NULL CONSTRAINT documents_doc_type_check CHECK (doc_type IN
                      ('purchase_invoice', 'sales_invoice', 'credit_note', 'debit_note', 'expense_bill', 'bank_statement',
                       'tally_xml', 'tally_export', 'other')),
    original_filename text NOT NULL CONSTRAINT documents_filename_ok CHECK (btrim(original_filename) <> '' AND original_filename !~ '[/\\]'),
    content_type      text NOT NULL CONSTRAINT documents_content_type_check CHECK (content_type IN
                      ('application/pdf', 'image/png', 'image/jpeg', 'image/tiff', 'application/xml')),
    size_bytes        bigint NOT NULL CONSTRAINT documents_size_positive CHECK (size_bytes > 0),
    sha256            text NOT NULL CONSTRAINT documents_sha256_format CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    -- generated by the service from client id + hash, never from the uploaded file name; relative, no '..', no leading '/' or drive letter
    storage_key       text NOT NULL CONSTRAINT documents_storage_key_safe CHECK (
                      storage_key ~ '^[a-z0-9][a-z0-9_./-]*$' AND storage_key !~ '\.\.' AND storage_key !~ '//' AND storage_key !~ '/$'),
    page_count        integer CONSTRAINT documents_page_count_positive CHECK (page_count IS NULL OR page_count > 0),
    status            text NOT NULL DEFAULT 'uploaded' CONSTRAINT documents_status_check
                      CHECK (status IN ('uploaded', 'text_ready', 'extracted', 'queued', 'done', 'failed')),
    status_note       text,
    uploaded_by       text NOT NULL CONSTRAINT documents_uploaded_by_not_blank CHECK (btrim(uploaded_by) <> ''),
    uploaded_at       timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT documents_id_client_key UNIQUE (id, client_id),
    CONSTRAINT documents_client_hash_key UNIQUE (client_id, sha256),   -- D-02: the same file is never stored twice for a client
    CONSTRAINT documents_storage_key_key UNIQUE (storage_key),
    CONSTRAINT documents_financial_year_fk FOREIGN KEY (financial_year_id, client_id) REFERENCES financial_years (id, client_id)
);
CREATE INDEX documents_client_idx ON documents (client_id, uploaded_at);

-- OCR / PDF text per page. Insert only: re-reading a file with another engine adds rows.
CREATE TABLE document_texts (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    client_id       uuid NOT NULL,
    document_id     uuid NOT NULL,
    page_no         integer NOT NULL CONSTRAINT document_texts_page_positive CHECK (page_no > 0),
