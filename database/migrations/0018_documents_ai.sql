-- =====================================================================================================
-- llm_calls: every model call (also a refused one), with the MASKED prompt and the raw answer. Insert only.
-- =====================================================================================================
CREATE TABLE llm_calls (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    client_id       uuid NOT NULL REFERENCES clients (id),
    document_id     uuid,
    purpose         text NOT NULL CONSTRAINT llm_calls_purpose_check CHECK (purpose IN ('invoice_extraction', 'narration_suggestion')),
    provider        text NOT NULL,
    model           text,
    prompt_version  text NOT NULL,
    prompt_masked   text,
    prompt_sha256   text CONSTRAINT llm_calls_prompt_sha_format CHECK (prompt_sha256 IS NULL OR prompt_sha256 ~ '^[0-9a-f]{64}$'),
    masking_applied boolean NOT NULL DEFAULT false,
    masking_report  jsonb,                     -- counts per kind of data masked, NEVER the masked values
    response_raw    text,
    status          text NOT NULL CONSTRAINT llm_calls_status_check
                    CHECK (status IN ('ok', 'invalid_json', 'schema_invalid', 'error', 'blocked')),
    error_message   text,
    tokens_in       integer CONSTRAINT llm_calls_tokens_in_nonneg CHECK (tokens_in IS NULL OR tokens_in >= 0),
    tokens_out      integer CONSTRAINT llm_calls_tokens_out_nonneg CHECK (tokens_out IS NULL OR tokens_out >= 0),
    latency_ms      integer CONSTRAINT llm_calls_latency_nonneg CHECK (latency_ms IS NULL OR latency_ms >= 0),
    created_by      text NOT NULL CONSTRAINT llm_calls_created_by_not_blank CHECK (btrim(created_by) <> ''),
    created_at      timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT llm_calls_id_client_key UNIQUE (id, client_id),
    CONSTRAINT llm_calls_document_fk FOREIGN KEY (document_id, client_id) REFERENCES documents (id, client_id),
    -- D-50: a call that reached a model carried a masked prompt (a refused call carries none)
    CONSTRAINT llm_calls_masked_before_sending CHECK (status = 'blocked' OR (prompt_masked IS NOT NULL AND masking_applied AND model IS NOT NULL)),
    CONSTRAINT llm_calls_blocked_sent_nothing CHECK (status <> 'blocked' OR (prompt_masked IS NULL AND response_raw IS NULL)),
    CONSTRAINT llm_calls_ok_has_response CHECK (status NOT IN ('ok', 'invalid_json', 'schema_invalid') OR response_raw IS NOT NULL),
    -- D-52: tripwire: an OpenRouter key must never end up in the audit text
    CONSTRAINT llm_calls_no_secret CHECK (coalesce(prompt_masked, '') !~ 'sk-or-' AND coalesce(response_raw, '') !~ 'sk-or-'
                                         AND coalesce(error_message, '') !~ 'sk-or-')
);
CREATE INDEX llm_calls_client_idx ON llm_calls (client_id, created_at);

-- =====================================================================================================
-- extractions: the validated JSON of one extraction (LLM or typed by the accountant). Never edited; edits live on the queue item.
