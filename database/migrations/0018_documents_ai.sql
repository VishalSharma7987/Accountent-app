    status           text NOT NULL DEFAULT 'pending' CONSTRAINT approval_queue_status_check
                     CHECK (status IN ('pending', 'in_review', 'accepted', 'rejected')),
    edited_payload   jsonb CONSTRAINT approval_queue_edited_object CHECK (edited_payload IS NULL OR jsonb_typeof(edited_payload) = 'object'),
    findings         jsonb NOT NULL DEFAULT '[]'::jsonb CONSTRAINT approval_queue_findings_array CHECK (jsonb_typeof(findings) = 'array'),
    blocking_count   integer NOT NULL DEFAULT 0 CONSTRAINT approval_queue_blocking_nonneg CHECK (blocking_count >= 0),  -- unresolved severity error + review
    warning_count    integer NOT NULL DEFAULT 0 CONSTRAINT approval_queue_warning_nonneg CHECK (warning_count >= 0),
    draft_voucher_id uuid,
    reviewer         text,
    acknowledged     jsonb CONSTRAINT approval_queue_ack_array CHECK (acknowledged IS NULL OR jsonb_typeof(acknowledged) = 'array'),
    accepted_by      text,
    accepted_at      timestamptz,
    rejected_by      text,
    rejected_at      timestamptz,
    reject_reason    text,
