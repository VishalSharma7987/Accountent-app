    CONSTRAINT approval_queue_document_fk FOREIGN KEY (document_id, client_id) REFERENCES documents (id, client_id),
    CONSTRAINT approval_queue_extraction_fk FOREIGN KEY (extraction_id, client_id) REFERENCES extractions (id, client_id),
    CONSTRAINT approval_queue_import_fk FOREIGN KEY (tally_import_id, client_id) REFERENCES tally_imports (id, client_id),
    CONSTRAINT approval_queue_voucher_fk FOREIGN KEY (draft_voucher_id, client_id) REFERENCES vouchers (id, client_id),
    CONSTRAINT approval_queue_kind_refs CHECK (
        (kind = 'invoice' AND extraction_id IS NOT NULL AND tally_import_id IS NULL)
        OR (kind = 'tally_voucher' AND tally_import_id IS NOT NULL AND btrim(coalesce(source_ref, '')) <> '' AND extraction_id IS NULL)),
    CONSTRAINT approval_queue_in_review_has_reviewer CHECK (status <> 'in_review' OR btrim(coalesce(reviewer, '')) <> ''),
    -- D-60: accepted = a person accepted it, a draft exists, and nothing blocking is left (errors are fixed, not acknowledged)
    CONSTRAINT approval_queue_accepted_complete CHECK (status <> 'accepted' OR
        (accepted_by IS NOT NULL AND accepted_at IS NOT NULL AND draft_voucher_id IS NOT NULL AND blocking_count = 0)),
    CONSTRAINT approval_queue_rejected_complete CHECK (status <> 'rejected' OR
        (rejected_by IS NOT NULL AND rejected_at IS NOT NULL AND btrim(coalesce(reject_reason, '')) <> '' AND draft_voucher_id IS NULL))
);
CREATE INDEX approval_queue_client_idx ON approval_queue_items (client_id, status, created_at);
CREATE UNIQUE INDEX approval_queue_voucher_key ON approval_queue_items (draft_voucher_id) WHERE draft_voucher_id IS NOT NULL;
-- one live item per extraction, and a Tally voucher is queued once (D-37) unless its earlier item was rejected
CREATE UNIQUE INDEX approval_queue_extraction_open_key ON approval_queue_items (extraction_id)
    WHERE extraction_id IS NOT NULL AND status <> 'rejected';
CREATE UNIQUE INDEX approval_queue_tally_ref_key ON approval_queue_items (client_id, source_ref)
    WHERE kind = 'tally_voucher' AND status <> 'rejected';

-- =====================================================================================================
-- Guards (the database refuses what the app must never do)
-- =====================================================================================================

-- plain insert-only tables
CREATE FUNCTION doc_insert_only_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    RAISE EXCEPTION '% rows cannot be changed or deleted (insert only)', TG_TABLE_NAME;
END $$;

CREATE TRIGGER document_texts_guard BEFORE UPDATE OR DELETE ON document_texts
    FOR EACH ROW EXECUTE FUNCTION doc_insert_only_guard();
CREATE TRIGGER llm_calls_guard BEFORE UPDATE OR DELETE ON llm_calls
    FOR EACH ROW EXECUTE FUNCTION doc_insert_only_guard();
CREATE TRIGGER tally_exports_guard BEFORE UPDATE OR DELETE ON tally_exports
    FOR EACH ROW EXECUTE FUNCTION doc_insert_only_guard();

-- documents: never deleted; the file identity never changes; status may move; doc_type only before an extraction exists
CREATE FUNCTION documents_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'a document cannot be deleted (it is evidence)';
    END IF;
    IF (to_jsonb(NEW) - 'status' - 'status_note' - 'page_count' - 'doc_type' - 'financial_year_id')
       <> (to_jsonb(OLD) - 'status' - 'status_note' - 'page_count' - 'doc_type' - 'financial_year_id') THEN
        RAISE EXCEPTION 'the file identity of a document (client, hash, storage key, size, name, type) cannot be changed';
    END IF;
    IF NEW.doc_type <> OLD.doc_type AND EXISTS (SELECT 1 FROM extractions WHERE document_id = OLD.id) THEN
        RAISE EXCEPTION 'the type of a document cannot be changed after an extraction exists';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER documents_guard BEFORE UPDATE OR DELETE ON documents
    FOR EACH ROW EXECUTE FUNCTION documents_guard();

-- document links: never updated; removed only while the voucher is still a draft
CREATE FUNCTION document_vouchers_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        RAISE EXCEPTION 'a document link cannot be changed (remove it and link again while the voucher is a draft)';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM vouchers WHERE id = OLD.voucher_id AND status = 'draft') THEN
        RAISE EXCEPTION 'a document link of an approved, posted or reversed voucher cannot be removed';
    END IF;
    RETURN OLD;
END $$;
CREATE TRIGGER document_vouchers_guard BEFORE UPDATE OR DELETE ON document_vouchers
    FOR EACH ROW EXECUTE FUNCTION document_vouchers_guard();

-- extractions: the AI's answer is evidence. Never edited, never deleted; the only change is being marked superseded (once),
-- and only when no live queue item still uses it (the item must be rejected first).
CREATE FUNCTION extractions_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'extractions cannot be deleted';
    END IF;
    IF OLD.superseded_at IS NOT NULL OR NEW.superseded_at IS NULL
       OR (to_jsonb(NEW) - 'superseded_at') <> (to_jsonb(OLD) - 'superseded_at') THEN
        RAISE EXCEPTION 'extractions are immutable (an extraction can only be marked superseded, once)';
    END IF;
    IF EXISTS (SELECT 1 FROM approval_queue_items WHERE extraction_id = OLD.id AND status <> 'rejected') THEN
        RAISE EXCEPTION 'this extraction is used by a queue item that is not rejected; reject that item before extracting again';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER extractions_guard BEFORE UPDATE OR DELETE ON extractions
    FOR EACH ROW EXECUTE FUNCTION extractions_guard();

-- narration suggestions: only the decision changes, once; never deleted
CREATE FUNCTION narration_suggestions_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'narration suggestions cannot be deleted';
    END IF;
    IF OLD.status <> 'suggested' OR NEW.status = 'suggested'
       OR (to_jsonb(NEW) - 'status' - 'decided_by' - 'decided_at') <> (to_jsonb(OLD) - 'status' - 'decided_by' - 'decided_at') THEN
        RAISE EXCEPTION 'a narration suggestion can only be accepted or rejected, once';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER narration_suggestions_guard BEFORE UPDATE OR DELETE ON narration_suggestions
    FOR EACH ROW EXECUTE FUNCTION narration_suggestions_guard();

-- queue items: created pending; path pending <-> in_review -> accepted | rejected (terminal); never deleted; identity never changes;
-- accepted needs a DRAFT voucher; findings / edited payload change only while pending or in review
CREATE FUNCTION approval_queue_items_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
DECLARE
    v_status text;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'a queue item cannot be deleted (reject it instead)';
    END IF;
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'pending' THEN
            RAISE EXCEPTION 'a queue item is created pending';
        END IF;
        RETURN NEW;
    END IF;
    IF OLD.status IN ('accepted', 'rejected') THEN
        RAISE EXCEPTION 'a % queue item cannot be changed', OLD.status;
    END IF;
    IF NEW.id <> OLD.id OR NEW.client_id <> OLD.client_id OR NEW.kind <> OLD.kind OR NEW.document_id <> OLD.document_id
       OR NEW.extraction_id IS DISTINCT FROM OLD.extraction_id OR NEW.tally_import_id IS DISTINCT FROM OLD.tally_import_id
       OR NEW.source_ref IS DISTINCT FROM OLD.source_ref OR NEW.created_by <> OLD.created_by OR NEW.created_at <> OLD.created_at THEN
        RAISE EXCEPTION 'the identity of a queue item cannot be changed';
    END IF;
    IF NEW.status <> OLD.status AND NOT (
        (OLD.status = 'pending' AND NEW.status IN ('in_review', 'accepted', 'rejected'))
        OR (OLD.status = 'in_review' AND NEW.status IN ('pending', 'accepted', 'rejected'))) THEN
        RAISE EXCEPTION 'a queue item cannot move from % to %', OLD.status, NEW.status;
    END IF;
    IF NEW.status = 'accepted' THEN
        SELECT status INTO v_status FROM vouchers WHERE id = NEW.draft_voucher_id AND client_id = NEW.client_id;
        IF v_status IS DISTINCT FROM 'draft' THEN
            RAISE EXCEPTION 'only an item whose draft voucher is still a draft can be accepted';
        END IF;
    END IF;
    NEW.updated_at := now();
    RETURN NEW;
END $$;
CREATE TRIGGER approval_queue_items_guard BEFORE INSERT OR UPDATE OR DELETE ON approval_queue_items
    FOR EACH ROW EXECUTE FUNCTION approval_queue_items_guard();

-- THE enforcement of "nothing wrong is ever posted": a voucher that sits in the queue cannot be approved or posted until its queue
-- item is accepted (and accepting needs no unresolved error / review finding, see approval_queue_accepted_complete).
CREATE FUNCTION vouchers_ai_queue_guard() RETURNS trigger
LANGUAGE plpgsql SET search_path FROM CURRENT AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM approval_queue_items q WHERE q.draft_voucher_id = NEW.id AND q.status <> 'accepted') THEN
        RAISE EXCEPTION 'this voucher was drafted from a document or an import and its queue item has not been accepted; accept it in the approval queue first';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER vouchers_ai_queue_guard BEFORE UPDATE OF status ON vouchers
    FOR EACH ROW WHEN (OLD.status IS DISTINCT FROM NEW.status AND NEW.status IN ('approved', 'posted'))
    EXECUTE FUNCTION vouchers_ai_queue_guard();

