    match_kind      text NOT NULL CONSTRAINT party_mappings_kind_check CHECK (match_kind IN ('gstin', 'name')),
    match_key       text NOT NULL,   -- gstin: upper-case GSTIN; name: lower-case, trimmed, single-spaced (done by the engine)
    party_ledger_id uuid NOT NULL,
    use_count       integer NOT NULL DEFAULT 0 CONSTRAINT party_mappings_use_count_nonneg CHECK (use_count >= 0),
    created_by      text NOT NULL CONSTRAINT party_mappings_created_by_not_blank CHECK (btrim(created_by) <> ''),
    created_at      timestamptz NOT NULL DEFAULT now(),
    last_used_at    timestamptz,
    CONSTRAINT party_mappings_key UNIQUE (client_id, match_kind, match_key),
    CONSTRAINT party_mappings_key_format CHECK (
        (match_kind = 'gstin' AND match_key ~ '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$')
        OR (match_kind = 'name' AND match_key = lower(btrim(match_key)) AND match_key <> '')),
