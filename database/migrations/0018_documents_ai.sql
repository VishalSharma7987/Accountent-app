    invalid_reason text,
    created_by     text NOT NULL CONSTRAINT extractions_created_by_not_blank CHECK (btrim(created_by) <> ''),
    created_at     timestamptz NOT NULL DEFAULT now(),
    superseded_at  timestamptz,
    CONSTRAINT extractions_id_client_key UNIQUE (id, client_id),
    CONSTRAINT extractions_version_key UNIQUE (document_id, version),
    CONSTRAINT extractions_document_fk FOREIGN KEY (document_id, client_id) REFERENCES documents (id, client_id),
    CONSTRAINT extractions_call_fk FOREIGN KEY (llm_call_id, client_id) REFERENCES llm_calls (id, client_id),
    CONSTRAINT extractions_llm_has_call CHECK (source <> 'llm' OR llm_call_id IS NOT NULL),
    CONSTRAINT extractions_invalid_has_reason CHECK (status = 'valid' OR btrim(coalesce(invalid_reason, '')) <> '')
);

